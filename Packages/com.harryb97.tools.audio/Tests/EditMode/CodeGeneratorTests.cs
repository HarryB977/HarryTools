using System.Collections.Generic;
using HarryTools.Audio.Editor;
using NUnit.Framework;
using UnityEngine;
using UnityEngine.TestTools;

namespace HarryTools.Audio.Tests {
    public class CodeGeneratorTests {
        // ==================== VARIABLES ===================
        private readonly List<Object> created = new List<Object>();

        // ==================== SETUP ===================
        [TearDown]
        public void TearDown() {
            for (int _i = 0; _i < created.Count; _i++) if (created[_i] != null) Object.DestroyImmediate(created[_i]);
            created.Clear();
        }

        private T Make<T>(string _name, string _id, string _group) where T : AudioCatalogItem {
            var _asset = ScriptableObject.CreateInstance<T>();
            _asset.name = _name;
            _asset.SetId(_id);
            _asset.SetGroupOverride(_group);
            created.Add(_asset);
            return _asset;
        }

        // ==================== TESTS ===================
        [Test]
        public void Generate_GroupsIntoNestedClasses() {
            var _items = new List<AudioCatalogItem> { Make<SoundAsset>("Wood", "aaa111", "Footsteps") };
            string _code = AudioCodeGenerator.Generate(_items, "Assets/Audio", "");
            StringAssert.Contains("public static class Sounds", _code);
            StringAssert.Contains("public static class Footsteps", _code);
            StringAssert.Contains("SoundRef Wood = new(\"aaa111\")", _code);
            StringAssert.StartsWith("// <auto-generated/>", _code);
        }

        [Test]
        public void Generate_NestedGroupPath_ProducesNestedClasses() {
            var _items = new List<AudioCatalogItem> { Make<SoundAsset>("Wood", "aaa111", "Footsteps/Indoor") };
            string _code = AudioCodeGenerator.Generate(_items, "Assets/Audio", "");
            StringAssert.Contains("public static class Footsteps", _code);
            StringAssert.Contains("public static class Indoor", _code);
        }

        [Test]
        public void Generate_AlwaysEmitsAllFourRoots() {
            string _code = AudioCodeGenerator.Generate(new List<AudioCatalogItem>(), "Assets/Audio", "");
            StringAssert.Contains("public static class Sounds", _code);
            StringAssert.Contains("public static class Music", _code);
            StringAssert.Contains("public static class Voices", _code);
            StringAssert.Contains("public static class Conversations", _code);
        }

        [Test]
        public void Generate_UsesTypedRefPerAssetType() {
            var _items = new List<AudioCatalogItem> {
                Make<MusicAsset>("Theme", "m1", ""),
                Make<VoiceAsset>("Hello", "v1", ""),
                Make<ConversationAsset>("Intro", "c1", ""),
            };
            string _code = AudioCodeGenerator.Generate(_items, "Assets/Audio", "");
            StringAssert.Contains("MusicRef Theme = new(\"m1\")", _code);
            StringAssert.Contains("VoiceRef Hello = new(\"v1\")", _code);
            StringAssert.Contains("ConversationRef Intro = new(\"c1\")", _code);
        }

        [Test]
        public void Generate_IsDeterministic() {
            var _a = Make<SoundAsset>("A", "1", "G");
            var _b = Make<SoundAsset>("B", "2", "G");
            var _c = Make<SoundAsset>("C", "3", "H/I");
            string _first = AudioCodeGenerator.Generate(new List<AudioCatalogItem> { _a, _b, _c }, "Assets/Audio", "X");
            string _second = AudioCodeGenerator.Generate(new List<AudioCatalogItem> { _c, _a, _b }, "Assets/Audio", "X");
            Assert.AreEqual(_first, _second);
        }

        [Test]
        public void Generate_NameCollision_AddsSuffix() {
            var _items = new List<AudioCatalogItem> {
                Make<SoundAsset>("Wood", "id1", "Footsteps"),
                Make<SoundAsset>("Wood", "id2", "Footsteps"),
            };
            LogAssert.Expect(LogType.Warning, new System.Text.RegularExpressions.Regex("Wood"));
            string _code = AudioCodeGenerator.Generate(_items, "Assets/Audio", "");
            StringAssert.Contains("SoundRef Wood = new(\"id1\")", _code);
            StringAssert.Contains("SoundRef Wood_2 = new(\"id2\")", _code);
        }

        [Test]
        public void Generate_MemberCollidingWithNestedClass_AddsItemSuffix() {
            var _items = new List<AudioCatalogItem> {
                Make<SoundAsset>("Footsteps", "id1", ""),
                Make<SoundAsset>("Wood", "id2", "Footsteps"),
            };
            string _code = AudioCodeGenerator.Generate(_items, "Assets/Audio", "");
            StringAssert.Contains("SoundRef FootstepsItem = new(\"id1\")", _code);
            StringAssert.Contains("public static class Footsteps", _code);
        }

        [Test]
        public void Generate_EmptyNamespace_NoNamespaceBlock() {
            string _code = AudioCodeGenerator.Generate(new List<AudioCatalogItem>(), "Assets/Audio", "");
            StringAssert.DoesNotContain("namespace", _code);
        }

        [Test]
        public void Generate_WithNamespace_WrapsInBlock() {
            string _code = AudioCodeGenerator.Generate(new List<AudioCatalogItem>(), "Assets/Audio", "Game.Audio");
            StringAssert.Contains("namespace Game.Audio", _code);
            StringAssert.Contains("using HarryTools.Audio;", _code);
        }

        [Test]
        public void GetGroupPath_UsesOverrideThenFolderRelativeToRoot() {
            var _sound = Make<SoundAsset>("A", "1", "Custom/Path");
            Assert.AreEqual("Custom/Path", AudioCodeGenerator.GetGroupPath(_sound, "Assets/Audio"));
        }

        [Test]
        public void GroupFromFolder_RelativeToRoot_OrParentFolderOutsideRoot() {
            Assert.AreEqual("Footsteps/Wood", AudioCodeGenerator.GroupFromAssetPath("Assets/Audio/Footsteps/Wood/A.asset", "Assets/Audio"));
            Assert.AreEqual("", AudioCodeGenerator.GroupFromAssetPath("Assets/Audio/A.asset", "Assets/Audio"));
            Assert.AreEqual("Other", AudioCodeGenerator.GroupFromAssetPath("Assets/Stuff/Other/A.asset", "Assets/Audio"));
            Assert.AreEqual("", AudioCodeGenerator.GroupFromAssetPath("", "Assets/Audio"));
        }
    }
}
