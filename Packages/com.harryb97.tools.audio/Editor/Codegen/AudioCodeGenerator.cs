using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;

namespace HarryTools.Audio.Editor {
    /// <summary> Generates compile-time constants for every audio asset so a rename or delete breaks the build instead of playing the wrong sound. </summary>
    internal static class AudioCodeGenerator {
        // ==================== TYPES ===================
        internal struct Options {
            public string Root;
            public string OutputPath;
            public string Namespace;
        }

        private sealed class Member {
            public string Name;
            public string RefType;
            public string Id;
        }

        private sealed class Node {
            public readonly string Name;
            public readonly SortedDictionary<string, Node> Children = new SortedDictionary<string, Node>(StringComparer.Ordinal);
            public readonly List<Member> Members = new List<Member>();
            public readonly List<Entry> Pending = new List<Entry>();
            public readonly HashSet<string> UsedMembers = new HashSet<string>(StringComparer.Ordinal);
            public Node(string _name) => Name = _name;
        }

        private struct Entry {
            public AudioCatalogItem Item;
            public int Root;
            public string Group;
            public string Name;
        }

        // ==================== VARIABLES ===================
        // Assets created by the edit mode tests must not rewrite the generated file mid-run.
        private const string TestFolder = "Assets/HarryToolsAudioTests_Temp/";
        private const string DefaultRoot = "Assets/Audio";
        private const string DefaultPath = "Assets/HarryTools/Audio/AudioIds.g.cs";

        // ==================== PUBLIC ===================
        public static string Generate(IReadOnlyList<AudioCatalogItem> _items, string _rootFolder, string _namespace) {
            var _roots = new[] { new Node("Sounds"), new Node("Music"), new Node("Voices"), new Node("Conversations") };

            var _entries = new List<Entry>(_items.Count);
            for (int _i = 0; _i < _items.Count; _i++) {
                AudioCatalogItem _item = _items[_i];
                if (_item == null || string.IsNullOrEmpty(_item.Id)) continue;
                int _root = RootIndex(_item);
                if (_root < 0) continue;
                _entries.Add(new Entry { Item = _item, Root = _root, Group = GetGroupPath(_item, _rootFolder), Name = _item.name });
            }
            _entries.Sort(CompareEntries);

            for (int _i = 0; _i < _entries.Count; _i++) {
                Entry _entry = _entries[_i];
                Node _node = _roots[_entry.Root];
                if (!string.IsNullOrEmpty(_entry.Group)) {
                    string[] _segments = _entry.Group.Split('/');
                    for (int _s = 0; _s < _segments.Length; _s++) {
                        if (string.IsNullOrWhiteSpace(_segments[_s])) continue;
                        string _segment = IdentifierSanitizer.ToIdentifier(_segments[_s]);
                        if (_segment == _node.Name) _segment += "Group";
                        if (!_node.Children.TryGetValue(_segment, out Node _child)) {
                            _child = new Node(_segment);
                            _node.Children.Add(_segment, _child);
                        }
                        _node = _child;
                    }
                }
                _node.Pending.Add(_entry);
            }
            for (int _i = 0; _i < _roots.Length; _i++) ResolveNames(_roots[_i]);

            var _sb = new StringBuilder();
            _sb.Append("// <auto-generated/>\n");
            _sb.Append("// Generated by HarryTools Audio. Do not edit; regenerate with Tools/HarryTools/Audio/Regenerate Ids.\n");
            _sb.Append("using HarryTools.Audio;\n\n");
            bool _hasNamespace = !string.IsNullOrEmpty(_namespace);
            int _indent = 0;
            if (_hasNamespace) {
                _sb.Append("namespace ").Append(_namespace).Append(" {\n");
                _indent = 1;
            }
            for (int _i = 0; _i < _roots.Length; _i++) {
                Emit(_sb, _roots[_i], _indent);
                if (_i < _roots.Length - 1) _sb.Append('\n');
            }
            if (_hasNamespace) _sb.Append("}\n");
            return _sb.ToString();
        }

        /// <summary> Group override, or the folder path relative to the root. </summary>
        public static string GetGroupPath(AudioCatalogItem _item, string _root) {
            if (_item == null) return string.Empty;
            if (!string.IsNullOrWhiteSpace(_item.GroupOverride)) return _item.GroupOverride.Trim('/', ' ');
            return GroupFromAssetPath(AssetDatabase.GetAssetPath(_item), _root);
        }

        /// <summary> Path relative to the root; outside the root it is the parent folder name. </summary>
        public static string GroupFromAssetPath(string _assetPath, string _root) {
            if (string.IsNullOrEmpty(_assetPath)) return string.Empty;
            string _folder = (Path.GetDirectoryName(_assetPath) ?? string.Empty).Replace('\\', '/');
            string _normalizedRoot = (_root ?? string.Empty).Replace('\\', '/').TrimEnd('/');
            if (_folder == _normalizedRoot) return string.Empty;
            if (_folder.StartsWith(_normalizedRoot + "/", StringComparison.Ordinal)) return _folder.Substring(_normalizedRoot.Length + 1);
            int _slash = _folder.LastIndexOf('/');
            return _slash >= 0 ? _folder.Substring(_slash + 1) : _folder;
        }

        public static void WriteIfChanged(string _path, string _content) {
            if (File.Exists(_path) && File.ReadAllText(_path) == _content) return;
            string _directory = Path.GetDirectoryName(_path);
            if (!string.IsNullOrEmpty(_directory)) Directory.CreateDirectory(_directory);
            File.WriteAllText(_path, _content, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(_path);
        }

        /// <summary> Regenerates the ids file from every audio asset in the project. </summary>
        public static void Regenerate() {
            Options _options = GetOptions();
            string[] _guids = AssetDatabase.FindAssets("t:AudioCatalogItem");
            var _items = new List<AudioCatalogItem>(_guids.Length);
            for (int _i = 0; _i < _guids.Length; _i++) {
                string _path = AssetDatabase.GUIDToAssetPath(_guids[_i]);
                if (_path.StartsWith(TestFolder, StringComparison.Ordinal)) continue;
                var _item = AssetDatabase.LoadAssetAtPath<AudioCatalogItem>(_path);
                if (_item == null) continue;
                AudioIdAssigner.EnsureId(_item);
                _items.Add(_item);
            }
            WriteIfChanged(_options.OutputPath, Generate(_items, _options.Root, _options.Namespace));
        }

        // ==================== INTERNAL ===================
        /// <summary> Single source of the generator settings. Task 4 redirects this to the project settings. </summary>
        internal static Options GetOptions() => new Options { Root = DefaultRoot, OutputPath = DefaultPath, Namespace = string.Empty };

        // ==================== EDITOR HOOKS ===================
        [InitializeOnLoadMethod]
        private static void Subscribe() {
            AudioCatalogMaintainer.Rebuilt -= Regenerate;
            AudioCatalogMaintainer.Rebuilt += Regenerate;
        }

        [MenuItem("Tools/HarryTools/Audio/Regenerate Ids")]
        private static void RegenerateMenu() => Regenerate();

        // ==================== PRIVATE ===================
        private static int CompareEntries(Entry _a, Entry _b) {
            int _result = _a.Root.CompareTo(_b.Root);
            if (_result != 0) return _result;
            _result = string.CompareOrdinal(_a.Group, _b.Group);
            if (_result != 0) return _result;
            _result = string.CompareOrdinal(_a.Name, _b.Name);
            if (_result != 0) return _result;
            return string.CompareOrdinal(_a.Item.Id, _b.Item.Id);
        }

        private static int RootIndex(AudioCatalogItem _item) {
            switch (_item) {
                case SoundAsset _: return 0;
                case MusicAsset _: return 1;
                case VoiceAsset _: return 2;
                case ConversationAsset _: return 3;
                default: return -1;
            }
        }

        private static string RefType(int _root) {
            switch (_root) {
                case 0: return "SoundRef";
                case 1: return "MusicRef";
                case 2: return "VoiceRef";
                default: return "ConversationRef";
            }
        }

        // Names are resolved once the tree is complete so members can detect nested classes with the same name.
        private static void ResolveNames(Node _node) {
            for (int _i = 0; _i < _node.Pending.Count; _i++) AddMember(_node, _node.Pending[_i]);
            _node.Pending.Clear();
            foreach (KeyValuePair<string, Node> _child in _node.Children) ResolveNames(_child.Value);
        }

        private static void AddMember(Node _node, Entry _entry) {
            string _name = IdentifierSanitizer.ToIdentifier(_entry.Name);
            if (_node.Children.ContainsKey(_name) || _name == _node.Name) _name += "Item";
            if (_node.UsedMembers.Contains(_name)) {
                int _n = 2;
                while (_node.UsedMembers.Contains(_name + "_" + _n)) _n++;
                string _unique = _name + "_" + _n;
                HarryTools.LoggerTool.Logger.LogWarning("Audio", $"Audio asset name '{_entry.Name}' is repeated in {_node.Name}; generated as {_unique}.");
                _name = _unique;
            }
            _node.UsedMembers.Add(_name);
            _node.Members.Add(new Member { Name = _name, RefType = RefType(_entry.Root), Id = _entry.Item.Id });
        }

        private static void Emit(StringBuilder _sb, Node _node, int _indent) {
            string _pad = new string(' ', _indent * 4);
            _sb.Append(_pad).Append("public static class ").Append(_node.Name).Append(" {\n");
            for (int _i = 0; _i < _node.Members.Count; _i++) {
                Member _member = _node.Members[_i];
                _sb.Append(_pad).Append("    public static readonly ").Append(_member.RefType).Append(' ').Append(_member.Name)
                    .Append(" = new(\"").Append(_member.Id.Replace("\\", "\\\\").Replace("\"", "\\\"")).Append("\");\n");
            }
            foreach (KeyValuePair<string, Node> _child in _node.Children) Emit(_sb, _child.Value, _indent + 1);
            _sb.Append(_pad).Append("}\n");
        }
    }
}
